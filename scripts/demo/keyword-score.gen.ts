// Generates lib/demo/keyword-score-data.ts, the Keyword Score Checker demo's data:
// nike.com's "best running shoes" buying guide, scored for that keyword. The page
// runs through the same pipeline runKeywordAnalysis.worker.ts uses (see pages.ts),
// and overallScore is the backend's own computeSeoScore() on the result.
//
// Run from freeserp-frontend-v2/ (needs freeserp-backend-v2 checked out next to it):
//   node scripts/demo/run.mjs scripts/demo/keyword-score.gen.ts

import { writeFileSync } from "node:fs"
import { computeSeoScore } from "../../../freeserp-backend-v2/src/modules/competitor-analysis/lib/seoScore"
import { crawlPage, crumbs, type PageSpec } from "./pages"

const KEYWORD = "best running shoes"
const AT = "2026-11-18T06:00:00.000Z"
const URL_ = "https://www.nike.com/a/best-running-shoes"

// A decent guide with clear room to improve: some images lack alt text, the
// Article schema has no author or modified date, it cites no outside sources,
// and it is slow on mobile.
const SPEC: PageSpec = {
  url: URL_,
  title: "Best Running Shoes: Our Picks for Every Runner. Nike.com",
  desc: "Find the best running shoes for you, from daily trainers to race-day super shoes. Compare cushioning, drop and fit to choose the right pair.",
  h1: "The Best Running Shoes for Every Kind of Run",
  sections: [
    { h2: "How to choose the best running shoes", paras: 2, h3: ["Cushioning", "Heel-to-toe drop", "Fit"] },
    { h2: "Best everyday running shoe: Pegasus 41", paras: 2 },
    { h2: "Best cushioned running shoe: Vomero 18", paras: 1 },
    { h2: "Best racing shoe: Vaporfly 3", paras: 1 },
    { h2: "Best trail running shoe: Pegasus Trail 5", paras: 1 },
  ],
  images: 12,
  altRatio: 0.75,
  external: [],
  schema: [crumbs(URL_, "Best Running Shoes"), { "@context": "https://schema.org", "@type": "Article", headline: "The Best Running Shoes for Every Kind of Run", datePublished: "2025-02-10" }],
  toc: true,
  breadcrumb: true,
  psi: [46, 92, 90, 81, 450, 1900, 3900, 520, 0.08],
  auth: [91, 58, 48_600_000, 6_400],
}

const { page, fullCrawlData, columns } = crawlPage(SPEC, KEYWORD, AT)
const seo = computeSeoScore(fullCrawlData as never, KEYWORD, URL_)

// The row kaService.get() returns (ka.repo.ts / markCompleted fields).
const analysis = {
  id: "demo",
  keyword: KEYWORD,
  url: URL_,
  domain: "nike.com",
  status: "COMPLETED",
  error: null,
  crawlData: fullCrawlData,
  crawlMethod: page.crawlMethod,
  overallScore: seo.total,
  ...columns,
  createdAt: new Date(Date.parse(AT) - 40_000).toISOString(),
  completedAt: AT,
}

const out = `// GENERATED by scripts/demo/keyword-score.gen.ts from the backend's own crawl
// parsing and scoring. Do not edit by hand; change the generator and rerun it.
/* eslint-disable */
export const GENERATED_AT = ${JSON.stringify(AT)}
export const ANALYSIS = ${JSON.stringify(analysis)}
`
writeFileSync("lib/demo/keyword-score-data.ts", out)
console.log(`lib/demo/keyword-score-data.ts: score ${seo.total} (${seo.grade}), ${(out.length / 1024).toFixed(0)} KB`)
